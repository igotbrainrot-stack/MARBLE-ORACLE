"""EXACT Oggcultist 2.0.6 theme textures, shared across Marble Oracle tabs.

The bundled PNGs are generated by the *actual* embedded Oggcultist
``oggcultist/gui/textures.py::grain`` function. Do not synthesize a second
noise algorithm here. Ttk's image elements tile these tiles behind text, as
in Oggcultist itself; no noisy overlay is ever drawn above the artwork.
This module needs only tkinter at runtime (Pillow is not required to draw).
"""
from __future__ import annotations
from pathlib import Path
import tkinter as tk
from tkinter import ttk

TEXTURES = Path(__file__).resolve().parent / 'data' / 'oggcultist_texture'
ROLE_COLOURS = {
    '#1d1714': 'page', '#261f1b': 'card', '#130f0d': 'side',
    '#16110f': 'sunken', '#1a1512': 'sunken_alt',
    '#2f2620': 'control', '#4a2c18': 'accent_soft',
}
FILES = {role: TEXTURES / f'{role}.png' for role in ('page','card','side','sunken','sunken_alt','control','accent_soft')}

def role_of(color, default='page'):
    return ROLE_COLOURS.get(str(color).lower(), default)

def png_bytes(role):
    """The unchanged PNG bytes generated by Oggcultist's own texture source."""
    return FILES[role].read_bytes()


def install(root):
    """Install source-image ttk elements in whichever theme is active now.

    Oggcultist switches the shared Tcl interpreter to the ``clam`` ttk theme
    when its tab opens. Ttk style layouts are theme-local, so on returning to
    Touch Type or Passphrase we must reapply the layouts to that theme.
    """
    root = root.winfo_toplevel()
    style = ttk.Style(root)
    theme = style.theme_use()
    state = getattr(root, '_marble_ogg_texture_styles', None)
    if state is None:
        state = {'photos': {role: tk.PhotoImage(master=root, file=str(path))
                            for role, path in FILES.items()}, 'themes': set()}
        root._marble_ogg_texture_styles = state
    if theme in state['themes']:
        return state['photos']
    known = set(style.element_names())
    for role, photo in state['photos'].items():
        element = f'Marble.Ogg.Grain.{role}'
        if element not in known:
            style.element_create(element, 'image', photo, sticky='nswe', width=1, height=1)
        style.layout(f'MarbleOgg.{role}.TFrame', [(element, {'sticky':'nswe'})])
        style.layout(f'MarbleOgg.{role}.TLabel', [(element, {'sticky':'nswe', 'children':[
            ('Label.padding', {'sticky':'nswe', 'children': [('Label.label', {'sticky':'nswe'})]})
        ]})])
    state['themes'].add(theme)
    return state['photos']


def frame(parent, *, bg=None, padx=0, pady=0, highlightthickness=0,
          highlightbackground=None, **opts):
    """Ttk frame whose body uses Oggcultist's same tiled PNG surface."""
    install(parent)
    role = role_of(bg, getattr(parent,'_marble_ogg_role','page'))
    if padx or pady:
        opts['padding'] = (padx, pady)
    # ttk image backgrounds are their own drawing elements. A 1px original
    # border is left to its surrounding parent rather than covered by grain.
    widget = ttk.Frame(parent, style=f'MarbleOgg.{role}.TFrame', **opts)
    widget._marble_ogg_role = role
    return widget


def label(parent, *, bg=None, fg=None, padx=0, pady=0, **opts):
    """Tiled ttk label: text stays above the source Oggcultist grain."""
    install(parent)
    role = role_of(bg, getattr(parent, '_marble_ogg_role', 'page'))
    if fg is not None:
        opts['foreground'] = fg
    if padx or pady:
        opts['padding'] = (padx,pady)
    widget = ttk.Label(parent, style=f'MarbleOgg.{role}.TLabel', **opts)
    widget._marble_ogg_role = role
    return widget
