"""EXACT Oggcultist 2.0.6 theme textures, shared across Marble Oracle tabs.

The bundled PNGs are generated by the *actual* embedded Oggcultist
``oggcultist/gui/textures.py::grain`` function. Do not synthesize a second
noise algorithm here. Ttk's image elements tile these tiles behind text, as
in Oggcultist itself; no noisy overlay is ever drawn above the artwork.
This module needs only tkinter at runtime (Pillow is not required to draw).
"""
from __future__ import annotations
from pathlib import Path
import tkinter as tk
from tkinter import ttk

TEXTURES = Path(__file__).resolve().parent / 'data' / 'oggcultist_texture'
ROLE_COLOURS = {
    '#1d1714': 'page', '#261f1b': 'card', '#130f0d': 'side',
    '#16110f': 'sunken', '#1a1512': 'sunken_alt',
    '#2f2620': 'control', '#4a2c18': 'accent_soft',
}
FILES = {role: TEXTURES / f'{role}.png' for role in ('page','card','side','sunken','sunken_alt','control','accent_soft')}
# Classic draws Oggcultist's film grain. Dark and Light (oracle_appearance) use a faint pumice instead
# (oracle_pumice, 0.5.2): use_pumice() swaps the tiles, keyed by the new palette's surface colours.
# ENABLED False gives flat widgets (no texture at all).
ENABLED = True
MODE = 'grain'
_PUMICE = {}
_KEPT = []      # texture PhotoImages live as long as the process


# 0.5.3: card-like surfaces are rounded in Dark / Light (pages and sidebars, which meet the window edge, are not).
ROUND_ROLES = ('card', 'sunken', 'sunken_alt', 'control', 'accent_soft')
ROUND_RADIUS = 10
_PUMICE_COLOURS = {}


def known_elements(style):
    return set(style.element_names())


def _round_style(style, name, role, ground):
    style.layout(name, [(f'Marble.Ogg.Round.{role}', {'sticky': 'nswe'})])
    style.configure(name, background=ground)


def use_pumice(role_colours):
    """Texture with pumice tiles on these surface colours: {'page': '#1C1C1E', 'card': ..., ...}."""
    global MODE, ROLE_COLOURS
    import oracle_pumice
    MODE = 'pumice'
    ROLE_COLOURS = {}
    for role in FILES:
        colour = role_colours.get(role, role_colours.get('page'))
        _PUMICE[role] = oracle_pumice.tile_png(colour)
        _PUMICE_COLOURS[role] = colour
        ROLE_COLOURS.setdefault(colour.lower(), role)

def _parent_bg(parent):
    try:
        return parent.cget('bg')
    except tk.TclError:
        from oggcultist_design_system import COLOR
        return COLOR['canvas']


def role_of(color, default='page'):
    return ROLE_COLOURS.get(str(color).lower(), default)

def png_bytes(role):
    """The unchanged PNG bytes generated by Oggcultist's own texture source (the pumice tile in Dark / Light)."""
    if MODE == 'pumice':
        return _PUMICE[role]
    return FILES[role].read_bytes()


_TILE_PHOTOS = {}


def tile_photo(master, role):
    """The PhotoImage of the tile for `role`: one per window and surface, shared by every widget that asks and
    kept for the life of the process (so garbage collection on a worker thread never frees one)."""
    key = (master.tk.interpaddr(), MODE, role)
    image = _TILE_PHOTOS.get(key)
    try:
        if image is not None and str(image) in master.tk.call('image', 'names'):
            return image
    except tk.TclError:
        pass
    if MODE == 'pumice':
        import base64
        image = tk.PhotoImage(master=master, data=base64.b64encode(_PUMICE[role]))
    else:
        image = tk.PhotoImage(master=master, file=str(FILES[role]))
    if key in _TILE_PHOTOS:
        _KEPT.append(_TILE_PHOTOS[key])
    _TILE_PHOTOS[key] = image
    return image


def install(root):
    """Install source-image ttk elements in whichever theme is active now.

    Oggcultist switches the shared Tcl interpreter to the ``clam`` ttk theme
    when its tab opens. Ttk style layouts are theme-local, so on returning to
    Touch Type or Passphrase we must reapply the layouts to that theme.
    """
    root = root.winfo_toplevel()
    style = ttk.Style(root)
    theme = style.theme_use()
    state = getattr(root, '_marble_ogg_texture_styles', None)
    if state is None:
        state = {'photos': {role: tile_photo(root, role) for role in FILES}, 'themes': set()}
        _KEPT.append(state['photos'])   # never freed by a worker thread's garbage collection (see oracle_widgets)
        root._marble_ogg_texture_styles = state
    if MODE == 'pumice' and 'round' not in state:
        import base64
        import oracle_pumice
        state['round'] = {role: tk.PhotoImage(master=root, data=base64.b64encode(
            oracle_pumice.rounded_tile_png(_PUMICE_COLOURS[role], ROUND_RADIUS))) for role in ROUND_ROLES}
        state['round_styles'] = {}
        _KEPT.append(state['round'])
    if theme in state['themes']:
        return state['photos']
    if MODE == 'pumice':
        for role, image in state['round'].items():
            element = f'Marble.Ogg.Round.{role}'
            if element not in known_elements(style):
                style.element_create(element, 'image', image, border=ROUND_RADIUS, sticky='nswe')
        for name, (role, ground) in state['round_styles'].items():
            _round_style(style, name, role, ground)
    known = known_elements(style)
    for role, photo in state['photos'].items():
        element = f'Marble.Ogg.Grain.{role}'
        if element not in known:
            style.element_create(element, 'image', photo, sticky='nswe', width=1, height=1)
        style.layout(f'MarbleOgg.{role}.TFrame', [(element, {'sticky':'nswe'})])
        style.layout(f'MarbleOgg.{role}.TLabel', [(element, {'sticky':'nswe', 'children':[
            ('Label.padding', {'sticky':'nswe', 'children': [('Label.label', {'sticky':'nswe'})]})
        ]})])
    state['themes'].add(theme)
    return state['photos']


def frame(parent, *, bg=None, padx=0, pady=0, highlightthickness=0,
          highlightbackground=None, rounded=True, **opts):
    """Ttk frame whose body uses Oggcultist's same tiled PNG surface (a flat frame when ENABLED is off)."""
    if not ENABLED:
        widget = tk.Frame(parent, bg=bg or _parent_bg(parent), padx=padx, pady=pady,
                          highlightthickness=highlightthickness,
                          highlightbackground=highlightbackground or (bg or _parent_bg(parent)), **opts)
        widget._marble_ogg_role = 'flat'
        return widget
    install(parent)
    role = role_of(bg, getattr(parent,'_marble_ogg_role','page'))
    if padx or pady:
        opts['padding'] = (padx, pady)
    style_name = f'MarbleOgg.{role}.TFrame'
    if MODE == 'pumice' and role in ROUND_ROLES and rounded:
        # 0.5.3: a rounded card; its corners show the surface it sits on.
        ground = surface_colour(parent, _PUMICE_COLOURS.get('page'))
        style_name = f'MarbleOgg.{role}.on{str(ground).lstrip("#").upper()}.TFrame'
        state = parent.winfo_toplevel()._marble_ogg_texture_styles
        if style_name not in state['round_styles']:
            state['round_styles'][style_name] = (role, ground)
            _round_style(ttk.Style(parent), style_name, role, ground)
    # ttk image backgrounds are their own drawing elements. A 1px original
    # border is left to its surrounding parent rather than covered by grain.
    widget = ttk.Frame(parent, style=style_name, **opts)
    widget._marble_ogg_role = role
    return widget


def label(parent, *, bg=None, fg=None, padx=0, pady=0, **opts):
    """Tiled ttk label: text stays above the source Oggcultist grain (a flat label when ENABLED is off)."""
    if not ENABLED:
        options = {('fg' if k == 'foreground' else k): v for k, v in opts.items()}
        if fg is not None:
            options['fg'] = fg
        if 'style' in options:
            options.pop('style')
        widget = tk.Label(parent, bg=bg or _parent_bg(parent), padx=padx, pady=pady, **options)
        widget._marble_ogg_role = 'flat'
        return widget
    install(parent)
    role = role_of(bg, getattr(parent, '_marble_ogg_role', 'page'))
    if fg is not None:
        opts['foreground'] = fg
    if padx or pady:
        opts['padding'] = (padx,pady)
    widget = ttk.Label(parent, style=f'MarbleOgg.{role}.TLabel', **opts)
    widget._marble_ogg_role = role
    return widget


def surface_colour(widget, default=None):
    """The colour a widget shows behind its children: its bg, or for a textured frame the base colour of its
    texture (0.5.3: rounded controls fill their corners with it)."""
    try:
        return widget.cget('bg')
    except (tk.TclError, AttributeError):
        pass
    role = getattr(widget, '_marble_ogg_role', None)
    if role:
        for colour, owner in ROLE_COLOURS.items():
            if owner == role:
                return colour
    try:
        return surface_colour(widget.master, default)
    except AttributeError:
        return default
